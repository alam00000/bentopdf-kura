const char* symbolCodeToName(int code) {
  if (code >= 0x20 && code <= 0x7E) return kSymbolNamesLow[code - 0x20];
  if (code >= 0xA0 && code <= 0xFE) return kSymbolNamesHigh[code - 0xA0];
  return nullptr;
}

std::string zapfCodeToName(int code) {
  if (code == 0x20) return "space";
  if (code >= 0x21 && code <= 0x7E) return "a" + std::to_string(code - 0x21 + 1);
  if (code >= 0xA1 && code <= 0xFF) return "a" + std::to_string(code - 0xA1 + 101);
  return std::string();
}
