uint16_t symbolToUnicode(int code) {
  if (code >= 0x20 && code < 0x80) return kSymbolLow[code - 0x20];
  if (code >= 0xA0 && code <= 0xFF) return kSymbolHigh[code - 0xA0];
  return 0;
}

uint16_t zapfDingbatsToUnicode(int code) {
  if (code == 0x20) return 0x0020;
  if (code >= 0x21 && code <= 0x7E) return static_cast<uint16_t>(0x2701 + (code - 0x21));
  if (code >= 0x80 && code <= 0x8D) return static_cast<uint16_t>(0x2768 + (code - 0x80));
  if (code >= 0xA1 && code <= 0xFF) return static_cast<uint16_t>(0x2761 + (code - 0xA1));
  return 0;
}

